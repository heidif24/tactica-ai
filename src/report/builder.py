def fig_to_png_bytes(fig) -> bytes:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=140, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    buf.seek(0)
    return buf.read()


def make_correlation_heatmap(df: pd.DataFrame) -> Optional[bytes]:
    num = df.select_dtypes(include="number")
    if num.shape[1] < 2:
        return None
    corr = num.corr()
    fig, ax = plt.subplots(figsize=(8, 6))
    sns.heatmap(corr, annot=True, fmt=".2f", cmap="RdBu_r", center=0, ax=ax, square=True)
    ax.set_title("Correlation heatmap")
    return fig_to_png_bytes(fig)


def make_missing_bar(df: pd.DataFrame) -> Optional[bytes]:
    miss = df.isna().mean() * 100
    miss = miss[miss > 0].sort_values(ascending=True)
    if miss.empty:
        return None
    fig, ax = plt.subplots(figsize=(8, max(3, 0.35 * len(miss))))
    miss.plot(kind="barh", ax=ax, color="#5B8FF9")
    ax.set_xlabel("Missing %")
    ax.set_title("Missing data by column")
    return fig_to_png_bytes(fig)


def make_distribution_grid(df: pd.DataFrame, max_cols: int = 4) -> Optional[bytes]:
    num = df.select_dtypes(include="number")
    cols = num.columns[:max_cols].tolist()
    if not cols:
        return None
    n = len(cols)
    fig, axes = plt.subplots(1, n, figsize=(3.2 * n, 3.2))
    if n == 1:
        axes = [axes]
    for ax, c in zip(axes, cols):
        ax.hist(num[c].dropna(), bins=25, color="#5B8FF9", edgecolor="white")
        ax.set_title(c, fontsize=9)
    fig.suptitle("Distributions", y=1.02)
    fig.tight_layout()
    return fig_to_png_bytes(fig)


def build_pdf_report(
    title: str,
    cleaning: CleaningReport,
    results: list,
    chart_pngs: list,
) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import inch
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
    from reportlab.lib import colors

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=0.7 * inch, bottomMargin=0.7 * inch)
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="BodyClear", parent=styles["Normal"], fontSize=10, leading=14))
    story = []

    story.append(Paragraph(title, styles["Title"]))
    story.append(Paragraph(f"Generated {datetime.now().strftime('%Y-%m-%d %H:%M')}", styles["Normal"]))
    story.append(Spacer(1, 12))

    story.append(Paragraph("Cleaning summary", styles["Heading2"]))
    for note in cleaning.notes:
        story.append(Paragraph(f"• {note}", styles["BodyClear"]))
    story.append(Spacer(1, 10))

    for res in results:
        story.append(Paragraph(res.title, styles["Heading2"]))
        story.append(Paragraph(res.summary.replace("**", ""), styles["BodyClear"]))
        story.append(Spacer(1, 6))
        for tname, tdf in res.tables.items():
            story.append(Paragraph(tname, styles["Heading3"]))
            show = tdf.head(25)
            data = [list(show.columns)] + show.astype(str).values.tolist()
            tbl = Table(data, repeatRows=1)
            tbl.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f2937")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f3f4f6")]),
            ]))
            story.append(tbl)
            story.append(Spacer(1, 10))

    for ctitle, png in chart_pngs:
        story.append(Paragraph(ctitle, styles["Heading2"]))
        img = Image(io.BytesIO(png), width=6.2 * inch, height=4.2 * inch, kind="proportional")
        story.append(img)
        story.append(Spacer(1, 12))

    story.append(Paragraph(
        "This report was generated by Lumen. It is for analysis and education.",
        styles["BodyClear"],
    ))
    doc.build(story)
    buffer.seek(0)
    return buffer.read()


def build_docx_report(title: str, cleaning: CleaningReport, results: list) -> bytes:
    from docx import Document

    doc = Document()
    doc.add_heading(title, 0)
    doc.add_paragraph(f"Generated {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    doc.add_heading("Cleaning summary", level=1)
    for note in cleaning.notes:
        doc.add_paragraph(note, style="List Bullet")

    for res in results:
        doc.add_heading(res.title, level=1)
        doc.add_paragraph(res.summary.replace("**", ""))
        for tname, tdf in res.tables.items():
            doc.add_heading(tname, level=2)
            show = tdf.head(30)
            table = doc.add_table(rows=1, cols=len(show.columns))
            table.style = "Table Grid"
            hdr = table.rows[0].cells
            for i, c in enumerate(show.columns):
                hdr[i].text = str(c)
            for _, row in show.iterrows():
                cells = table.add_row().cells
                for i, v in enumerate(row):
                    cells[i].text = str(v)

    doc.add_paragraph("This report was generated by Lumen.")
    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf.read()
